#!/usr/bin/env node
// Protocol fixtures (spec 009, plan 6.4): the reader's follow lab and social each keep a copy of the room protocol until
// milestone P6. fixtures/protocol.v1.json holds inputs and the results the READER's code gives for them; the contract test
// (src/protocol.contract.test.ts) replays them against this package, so a change on our side that alters a result fails CI.
//
//   npm run fixtures -w @sefaria-social/session -- --check <reader checkout>   compare the reader's results with the file
//   npm run fixtures -w @sefaria-social/session -- --write <reader checkout>   re-record the file from the reader
//
// <reader checkout> is the root of a Sefaria-Project checkout (with reader-next/node_modules installed). Run --check when
// re-pinning (setup checklist): a case the reader now answers differently is drift, named here, to resolve on purpose.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const pkg = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURE = path.join(pkg, "fixtures", "protocol.v1.json");
const INPUTS = path.join(pkg, "fixtures", "protocol.v1.inputs.json");

/** Runs the evaluator against one copy of the protocol code. */
export function evaluate(sessionDir, tsconfig) {
  const tsx = path.join(pkg, "..", "..", "node_modules", ".bin", "tsx");
  const args = [
    ...(tsconfig && existsSync(tsconfig) ? ["--tsconfig", tsconfig] : []),
    path.join(pkg, "scripts", "evaluate.mts"),
    sessionDir,
  ];
  const run = spawnSync(tsx, args, { input: readFileSync(INPUTS), encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (run.status !== 0) throw new Error(`evaluating ${sessionDir} failed:\n${run.stderr}`);
  return JSON.parse(run.stdout);
}

/** The reader's results for every input, in the fixture file's shape. */
export function recordFrom(checkout) {
  const root = path.join(checkout, "reader-next");
  const out = evaluate(path.join(root, "src", "lib", "session"), path.join(root, "tsconfig.json"));
  const inputs = JSON.parse(readFileSync(INPUTS, "utf8"));
  const commit = spawnSync("git", ["-C", checkout, "rev-parse", "HEAD"], { encoding: "utf8" }).stdout.trim() || null;
  return {
    $comment: "Generated by `npm run fixtures -w @sefaria-social/session -- --write <reader checkout>`. Do not edit by hand.",
    recordedFrom: { repo: "Sefaria/Sefaria-Project", commit },
    constants: out.constants,
    room: inputs.room.map((c, i) => ({ name: c.name, input: c.input, expected: out.room[i] })),
    client: inputs.client.map((c, i) => ({ name: c.name, input: c.input, expected: out.client[i] })),
  };
}

/** Names of the cases (and constants) whose results differ between two fixture objects. */
export function differences(a, b) {
  const diffs = [];
  if (JSON.stringify(a.constants) !== JSON.stringify(b.constants)) diffs.push("constants (LIMITS or PROTOCOL_VERSION)");
  for (const side of ["room", "client"]) {
    const names = new Set([...a[side].map((c) => c.name), ...b[side].map((c) => c.name)]);
    for (const name of names) {
      const x = a[side].find((c) => c.name === name);
      const y = b[side].find((c) => c.name === name);
      if (JSON.stringify(x?.expected) !== JSON.stringify(y?.expected)) diffs.push(`${side}: ${name}`);
    }
  }
  return diffs;
}

export function main(argv, log = console.log, err = console.error) {
  const mode = argv[0];
  const checkout = argv[1];
  if (!["--check", "--write"].includes(mode) || !checkout) {
    err("usage: fixtures.mjs --check|--write <Sefaria-Project checkout>");
    return 2;
  }
  const fresh = recordFrom(path.resolve(checkout));
  if (mode === "--write") {
    writeFileSync(FIXTURE, JSON.stringify(fresh, null, 2) + "\n");
    log(`fixtures: wrote ${path.relative(process.cwd(), FIXTURE)} from ${fresh.recordedFrom.commit}`);
    return 0;
  }
  const diffs = differences(JSON.parse(readFileSync(FIXTURE, "utf8")), fresh);
  if (diffs.length === 0) {
    log(`fixtures: PASS (the reader at ${fresh.recordedFrom.commit} gives every recorded result)`);
    return 0;
  }
  err(
    [
      `fixtures: FAIL (the reader at ${fresh.recordedFrom.commit} answers ${diffs.length} case(s) differently)`,
      ...diffs.map((d) => `  x ${d}`),
      "  fix: the protocol drifted. Bring packages/session in line with the reader (or agree the change with the reader's",
      "  owners), then re-record with --write and commit the fixture with the code change.",
    ].join("\n"),
  );
  return 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  process.exit(main(process.argv.slice(2)));
