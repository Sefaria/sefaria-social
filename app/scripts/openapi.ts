// `npm run api:generate`: write packages/api-client/openapi.json (from the endpoint contracts) and the client's TypeScript
// types packages/api-client/src/schema.ts (openapi-typescript). Commit both; CI compares them with a fresh generation.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { buildOpenApi, renderOpenApi } from "../src/server/api/openapi";

export const OPENAPI_FILE = fileURLToPath(new URL("../../packages/api-client/openapi.json", import.meta.url));
export const SCHEMA_FILE = fileURLToPath(new URL("../../packages/api-client/src/schema.ts", import.meta.url));

const HEADER = `// Generated by \`npm run api:generate\` from packages/api-client/openapi.json (openapi-typescript). Do not edit.
`;

export async function renderClientTypes(openapiJson: string): Promise<string> {
  const ast = await openapiTS(JSON.parse(openapiJson) as Parameters<typeof openapiTS>[0], { alphabetize: true });
  return HEADER + astToString(ast);
}

export async function generated(): Promise<{ openapi: string; schema: string }> {
  const openapi = renderOpenApi(buildOpenApi());
  return { openapi, schema: await renderClientTypes(openapi) };
}

export const committed = () => ({ openapi: readFileSync(OPENAPI_FILE, "utf8"), schema: readFileSync(SCHEMA_FILE, "utf8") });

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { openapi, schema } = await generated();
  writeFileSync(OPENAPI_FILE, openapi);
  writeFileSync(SCHEMA_FILE, schema);
  console.log("api:generate: wrote packages/api-client/openapi.json and packages/api-client/src/schema.ts");
}
